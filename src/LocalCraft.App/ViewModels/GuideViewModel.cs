public sealed class FeatureGuideItem
{
    public required string Key { get; init; }
    public required string Title { get; init; }
    public required string Badge { get; init; }
    public required string IconData { get; init; }
    public required string Category { get; init; }
    public required string Purpose { get; init; }
    public required string Scenarios { get; init; }
    public required string Usage { get; init; }
    public required string Options { get; init; }
    public required string Result { get; init; }
    public required string Safety { get; init; }
    public required string Caveats { get; init; }
    public required string Example { get; init; }
    public required Brush CategoryBrush { get; init; }
    public required Brush CategorySoftBrush { get; init; }
}

public sealed class GuideViewModel : ViewModelBase
{
    private FeatureGuideItem? _selectedFeature;
    private bool _isDetailOpen;

    public GuideViewModel()
    {
        OpenDetailCommand = new RelayCommand(parameter =>
        {
            string? key = parameter?.ToString();
            SelectedFeature = Items.FirstOrDefault(x => string.Equals(x.Key, key, StringComparison.OrdinalIgnoreCase));
        });
        CloseDetailCommand = new RelayCommand(() => IsDetailOpen = false);
    }

    public ObservableCollection<FeatureGuideItem> Items { get; } = new();
    public RelayCommand OpenDetailCommand { get; }
    public RelayCommand CloseDetailCommand { get; }

    public FeatureGuideItem? SelectedFeature
    {
        get => _selectedFeature;
        private set
        {
            if (!SetProperty(ref _selectedFeature, value)) return;
            IsDetailOpen = value is not null;
        }
    }

    public bool IsDetailOpen
    {
        get => _isDetailOpen;
        set => SetProperty(ref _isDetailOpen, value);
    }

